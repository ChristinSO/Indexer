import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';

const browser = await chromium.launch({headless: true});
try {
  const page = await browser.newPage({viewport: {width: 1440, height: 1000}, reducedMotion: 'reduce'});
  const errors = [];
  let searchCalls = 0;
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.url().endsWith('/api/search')) searchCalls++; });
  await page.goto('http://127.0.0.1:8766');
  await page.locator('.photo-open').nth(19).waitFor();
  assert.equal(await page.getByText('Recently added', {exact: true}).count(), 0);
  assert.equal(await page.locator('.gallery-end').count(), 0);
  assert.equal(await page.locator('aside nav button').count(), 2);
  const ranked = page.getByRole('button', {name: 'Ranked search', exact: true});
  const filtered = page.getByRole('button', {name: 'Filtered search', exact: true});
  const searchBox = await page.getByRole('search').boundingBox();
  const modes = await page.getByRole('group', {name: 'Search mode', exact: true}).boundingBox();
  assert.ok(modes.x >= searchBox.x + searchBox.width);
  assert.ok(Math.abs(modes.y + modes.height / 2 - searchBox.y - searchBox.height / 2) < 2);
  await ranked.hover();
  await page.getByRole('tooltip').waitFor();
  assert.match(await page.getByRole('tooltip').innerText(), /No cutoff/);
  await ranked.focus();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('tooltip').count(), 0);
  await filtered.hover();
  assert.match(await page.getByRole('tooltip').innerText(), /70% or higher/);
  await page.screenshot({path: '.local/search-mode-tooltip.png'});
  await page.mouse.move(5, 5);
  assert.equal(await page.locator('.match-badge').count(), 0);
  assert.equal(await page.getByText('Private by design', {exact: true}).count(), 0);
  assert.equal(await page.locator('header').getByRole('button', {name: 'Settings'}).count(), 0);
  await page.getByRole('button', {name: 'Settings', exact: true}).click();
  await page.getByRole('button', {name: 'Close settings'}).click();
  await page.getByRole('textbox', {name: 'Describe a photo'}).fill('a cat');
  const responsePromise = page.waitForResponse(response => response.url().endsWith('/api/search'));
  await page.getByRole('button', {name: 'Search photos', exact: true}).click();
  const response = await responsePromise;
  assert.equal(response.status(), 200);
  const result = await response.json();
  await page.getByText('Ranked by relevance').waitFor();
  assert.equal(await page.locator('.match-badge').count(), 20);
  const scores = result.hits.map(hit => Math.round(Math.max(0, Math.min(1, hit.score)) * 1000) / 10);
  assert.deepEqual(await page.locator('.match-badge').allTextContents(), scores.map(score => `${score.toFixed(1)}%`));
  await page.screenshot({path: '.local/search-sorted.png', fullPage: true});
  await page.getByRole('button', {name: 'Filtered search', exact: true}).click();
  const expected70 = scores.filter(score => score >= 70).length;
  assert.equal(await page.locator('.photo-open').count(), expected70);
  assert.ok(expected70 > 0 && expected70 < 20);
  await page.mouse.move(5, 5);
  await page.screenshot({path: '.local/search-definitive.png', fullPage: true});
  await page.getByRole('button', {name: '80%', exact: true}).click();
  assert.equal(await page.locator('.photo-open').count(), scores.filter(score => score >= 80).length);
  if (!scores.some(score => score >= 80)) await page.getByText('No photos meet the 80% cutoff').waitFor();
  const slider = page.getByRole('slider', {name: /Minimum match/});
  await slider.fill('100');
  await page.getByText('No photos meet the 100% cutoff').waitFor();
  await page.getByRole('button', {name: 'Show ranked results'}).click();
  assert.equal(await page.locator('.photo-open').count(), 20);
  await page.getByRole('button', {name: 'Filtered search', exact: true}).click();
  await slider.fill('0');
  assert.equal(await page.locator('.photo-open').count(), 20);
  await page.getByRole('button', {name: '70%', exact: true}).click();
  const badge = await page.locator('.match-badge').first().boundingBox();
  const tile = await page.locator('.photo-tile').first().boundingBox();
  const star = await page.locator('.favorite-button').first().boundingBox();
  assert.ok(Math.abs(tile.x + tile.width - badge.x - badge.width - 9) < 1);
  assert.ok(star.y >= badge.y + badge.height);
  assert.equal(searchCalls, 1, 'Switching modes/cutoff must not repeat inference');
  for (const width of [820, 320, 390]) {
    await page.setViewportSize({width, height: 844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    const inputBox = await page.getByRole('search').boundingBox();
    const groupBox = await page.getByRole('group', {name: 'Search mode', exact: true}).boundingBox();
    assert.ok(groupBox.x >= inputBox.x + inputBox.width);
    assert.ok(Math.abs(groupBox.y + groupBox.height / 2 - inputBox.y - inputBox.height / 2) < 2);
    assert.equal(await ranked.locator('.mode-label').isVisible(), width > 760);
    assert.equal(await filtered.locator('.mode-label').isVisible(), width > 760);
  }
  await ranked.click();
  assert.equal(await page.locator('.photo-open').count(), 20);
  await filtered.click();
  assert.equal(await page.locator('.photo-open').count(), expected70);
  await page.getByRole('textbox', {name: 'Describe a photo'}).focus();
  await page.mouse.move(5, 5);
  await page.screenshot({path: '.local/search-definitive-mobile.png', fullPage: true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', {name: 'Clear search'}).click();
  assert.equal(await page.locator('.match-badge').count(), 0);
  assert.equal(await page.locator('.photo-open').count(), 20);
  await page.getByRole('button', {name: 'Toggle navigation'}).click();
  await page.getByRole('button', {name: 'Settings', exact: true}).click();
  await page.getByRole('button', {name: 'Close settings'}).click();
  assert.deepEqual(errors, []);
  const report = {searchCalls, sortedCount: 20, definitive70Count: expected70, scores, errors};
  fs.writeFileSync('.local/search-modes-qa.json', JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} finally { await browser.close(); }
